#!/usr/bin/env bash
# Write ADMIN-ACCESS.md: every credential and access detail this deployment has,
# in one place, in a file .gitignore keeps out of the repository.
#
# It is generated rather than written by hand so it cannot drift from .env — the
# file that is wrong about which wallet is an operator is worse than no file.
#
# Usage:  scripts/write-admin-access.sh
set -euo pipefail

cd "$(dirname "$0")/.."

OUT="ADMIN-ACCESS.md"
ENV_FILE=".env"

[[ -f "$ENV_FILE" ]] || { echo "error: no $ENV_FILE to read" >&2; exit 1; }

# shellcheck disable=SC1090
set -a; . "./$ENV_FILE"; set +a

WALLET_ADDR="$(solana address 2>/dev/null || echo '')"
KEYPAIR_PATH="${HOME}/.config/solana/id.json"
PROGRAM_ID="${HUSTLEON_PAY_PROGRAM_ID:-}"
if [[ -z "$PROGRAM_ID" && -f contracts/target/deploy/hustleon_pay-keypair.json ]]; then
  PROGRAM_ID="$(solana address -k contracts/target/deploy/hustleon_pay-keypair.json 2>/dev/null || echo '')"
fi

# Redact the password half of a DSN for the summary line, keeping enough of the
# host and role to identify which connection string it is.
redact() { sed -E 's#(://[^:]+:)[^@]*@#\1***@#' <<<"$1"; }

{
cat <<EOF
# Admin access — Hustle On

**This file is gitignored. Do not commit it, paste it into an issue, or send it to
anyone.** It is generated by \`scripts/write-admin-access.sh\`; re-run that after
changing anything in \`.env\`.

Generated: $(date -u '+%Y-%m-%d %H:%M UTC')

---

## Signing in

**There is no password anywhere in this system, and no email.** There is nothing
to reset and nothing to leak from a credential database, because the only thing
that can authenticate an account is an ed25519 signature from a Solana wallet.

The flow, which is the whole of it:

1. The browser asks the API for a challenge (\`POST /v1/auth/signin/challenge\`).
2. Your wallet is asked to sign a message naming this site, your address, and a
   one-time nonce.
3. The API verifies the signature and starts a session
   (\`POST /v1/auth/signin/verify\`).

The first time an address does this, the account is created. There is no separate
sign-up step.

### Operator wallets

A wallet listed in \`ADMIN_WALLETS\` is promoted to admin the first time it signs
in, and the promotion is written to the audit log. Admin access is a property of
the environment, not of a database row: restoring a backup or provisioning a new
deployment cannot silently drop it.

Configured now:

EOF

if [[ -n "${ADMIN_WALLETS:-}" ]]; then
  echo "${ADMIN_WALLETS}" | tr ',' '\n' | while read -r addr; do
    addr="$(echo "$addr" | tr -d '[:space:]')"
    [[ -n "$addr" ]] && echo "- \`$addr\`"
  done
else
  echo "- **none — nobody can reach the console.** Set ADMIN_WALLETS in .env."
fi

cat <<EOF

To add your own wallet, copy its address out of your wallet app (Phantom → your
account → copy address) and append it:

\`\`\`bash
# in .env, comma-separated, no spaces
ADMIN_WALLETS=$( [[ -n "${ADMIN_WALLETS:-}" ]] && echo "${ADMIN_WALLETS},<your-address>" || echo "<your-address>" )
\`\`\`

Then restart the API (\`make dev\`) and sign in with that wallet. The promotion is
automatic and one-time.

### The console

- Admin console: \`${ADMIN_PUBLIC_URL:-http://localhost:3002}/admin\` — signing in
  as an operator is what unlocks it.
- Admin sessions expire after \`${ADMIN_SESSION_MAX_AGE_HOURS:-12}\` hours by
  default, regardless of the ordinary session length.
- \`ADMIN_ALLOWED_IPS\`$( [[ -n "${ADMIN_ALLOWED_IPS:-}" ]] && echo " is set to \`${ADMIN_ALLOWED_IPS}\`" || echo " is **unset**, so the console is reachable from anywhere for a signed-in operator. Set it to a CIDR list to pin it to your network." )

---

## Database

The API connects as a least-privilege role. It can read and write data, and it
**cannot** delete an account, a timelapse or a donation, cannot touch the audit
trail, and cannot read the migration ledger. Those limits are enforced by
Postgres role grants, not by application code.

- API connection (role \`hustleon_api\`, inherits \`sardhana_app\`):
  \`$(redact "${DATABASE_URL:-unset}")\`
- Owner connection, used by migrations only:
  \`$(redact "${DATABASE_URL_DIRECT:-unset}")\`

Both full connection strings, passwords included, are in \`.env\`. To rotate the
API's password:

\`\`\`bash
scripts/create-api-role.sh --write-env   # new password, rewrites DATABASE_URL only
\`\`\`

Verify the limits are real rather than assumed:

\`\`\`bash
make preflight
\`\`\`

---

## Secrets

Both live in \`.env\` and are symlinked to \`frontend/.env.local\` and
\`admin/.env.local\`, so the web app and the API always read the same values.

| Variable | Purpose | Rotate by |
|---|---|---|
| \`SESSION_SECRET\` | Signs session tokens and CSRF tokens. Changing it invalidates every session, everywhere. | \`openssl rand -base64 48\`, then restart |
| \`INTERNAL_PROXY_SECRET\` | Lets the web app's server-side renders be rate limited per visitor, and stops anyone else from claiming a proxy header. | \`openssl rand -base64 48\`, then restart |

Current values:

\`\`\`
SESSION_SECRET=${SESSION_SECRET:-unset}
INTERNAL_PROXY_SECRET=${INTERNAL_PROXY_SECRET:-unset}
\`\`\`

---

## Solana

| | |
|---|---|
| Cluster | \`${SOLANA_CLUSTER:-devnet}\` |
| RPC | \`${SOLANA_RPC_URL:-https://api.devnet.solana.com}\` |
| Sponsorship program | $( [[ -n "$PROGRAM_ID" ]] && echo "\`$PROGRAM_ID\`" || echo "_not deployed — sponsorships are verified as plain transfers and leave no on-chain record_" ) |
| Deployer / operator keypair | \`$KEYPAIR_PATH\`$( [[ -n "$WALLET_ADDR" ]] && echo " (address \`$WALLET_ADDR\`)" ) |

That keypair is the program's upgrade authority **and** an operator wallet if its
address is in \`ADMIN_WALLETS\`. Back it up somewhere you control. Anyone holding
it can upgrade the program and sign in as an administrator.

Program wallet balance:

\`\`\`bash
solana balance --url ${SOLANA_RPC_URL:-https://api.devnet.solana.com}
\`\`\`

Deploying or redeploying the program:

\`\`\`bash
scripts/deploy-program.sh --check   # what it will cost, changes nothing
scripts/deploy-program.sh           # build, deploy, write .env
\`\`\`

A devnet deploy needs roughly 1.6 SOL of rent plus a refundable buffer. Get SOL
from <https://faucet.solana.com> — it needs a signed-in session, so it cannot be
automated from a script.

