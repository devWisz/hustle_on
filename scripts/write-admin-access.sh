## If you are locked out

**No admin wallet works.** The console is unreachable. Check, in order:
\`ADMIN_WALLETS\` in \`.env\` is set and the address is exactly right (base58 is
case-sensitive — one wrong character is a different wallet); the API was
restarted after the change; the wallet you are signing with is the one in the
list. \`make preflight\` checks all of this and names the offending value.

**You lost the wallet.** There is no recovery, by design — no seed phrase is held
anywhere, so there is nothing to recover from and nothing to steal. Add a
different wallet to \`ADMIN_WALLETS\`, restart, and sign in with that.

**Everything is down.** The database and secrets above are enough to bring up a
new instance: set \`DATABASE_URL\`, \`SESSION_SECRET\`, \`ADMIN_WALLETS\` and
\`WEB_PUBLIC_URL\` on the host and start the API. \`SESSION_SECRET\` must match the
old one if you want existing sessions to survive.
EOF
} > "$OUT"

chmod 600 "$OUT"
echo "wrote $OUT ($(wc -l < "$OUT" | tr -d ' ') lines, mode 600, gitignored)"
